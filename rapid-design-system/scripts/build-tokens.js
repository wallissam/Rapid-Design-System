#!/usr/bin/env node

/**
 * Rapid Design System — Token Build Pipeline
 *
 * Single entry point that reads the canonical JSON token files and
 * emits every downstream artefact:
 *   • packages/css/global.css        – :root + [data-theme="dark"] custom properties
 *   • packages/css/utilities.css     – .rapid-* utility classes
 *   • packages/fluent-adapter/index.ts – Fluent UI v9 theme object → CSS var() refs
 *   • packages/adapters/bryntum.css  – Third-party variable mapping template
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const TOKENS_DIR = path.join(ROOT, "tokens");
const CSS_DIR = path.join(ROOT, "packages", "css");
const FLUENT_DIR = path.join(ROOT, "packages", "fluent-adapter");
const ADAPTERS_DIR = path.join(ROOT, "packages", "adapters");

const PREFIX = "rapid";

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function readJSON(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf-8"));
}

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

/**
 * Flatten a nested object into { "color-brand-primary": "#0f6cbd", … }
 * Separator between nesting levels is a hyphen.
 */
function flatten(obj, parentKey = "") {
  const entries = [];
  for (const [key, value] of Object.entries(obj)) {
    const fullKey = parentKey ? `${parentKey}-${key}` : key;
    if (typeof value === "object" && value !== null && !Array.isArray(value)) {
      entries.push(...flatten(value, fullKey));
    } else {
      entries.push([fullKey, value]);
    }
  }
  return entries;
}

/**
 * Convert a flat token key to a CSS custom property name.
 * e.g. "color-brand-primary" → "--rapid-color-brand-primary"
 */
function toCSSVar(flatKey) {
  return `--${PREFIX}-${flatKey}`;
}

/**
 * Convert a flat token key to a camelCase JS identifier.
 * e.g. "color-brand-primary" → "colorBrandPrimary"
 */
function toCamelCase(flatKey) {
  return flatKey.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());
}

// ---------------------------------------------------------------------------
// 1. Build global.css — :root + [data-theme="dark"]
// ---------------------------------------------------------------------------

function buildGlobalCSS(baseTokens, darkTokens) {
  const baseEntries = flatten(baseTokens);
  const darkEntries = flatten(darkTokens);

  let css = `/* ============================================================\n`;
  css += ` * Rapid Design System — Global CSS Custom Properties\n`;
  css += ` * AUTO-GENERATED by scripts/build-tokens.js — DO NOT EDIT\n`;
  css += ` * ============================================================ */\n\n`;

  css += `:root {\n`;
  for (const [key, value] of baseEntries) {
    css += `  ${toCSSVar(key)}: ${value};\n`;
  }
  css += `}\n\n`;

  css += `[data-theme="dark"] {\n`;
  for (const [key, value] of darkEntries) {
    css += `  ${toCSSVar(key)}: ${value};\n`;
  }
  css += `}\n`;

  return css;
}

// ---------------------------------------------------------------------------
// 2. Build utilities.css — Lightweight utility classes
// ---------------------------------------------------------------------------

/**
 * Generates a set of utility classes that reference the CSS custom properties.
 * Pattern: .rapid-{category}-{name} { <property>: var(--rapid-…); }
 */
function buildUtilitiesCSS(baseTokens) {
  const lines = [];

  lines.push(`/* ============================================================`);
  lines.push(` * Rapid Design System — Utility Classes`);
  lines.push(` * AUTO-GENERATED by scripts/build-tokens.js — DO NOT EDIT`);
  lines.push(` * ============================================================ */`);
  lines.push(``);

  const colorEntries = flatten(baseTokens.color || {}, "color");
  for (const [key] of colorEntries) {
    const varRef = `var(${toCSSVar(key)})`;
    const cls = `${PREFIX}-bg-${key.replace(/^color-/, "")}`;
    lines.push(`.${cls} { background-color: ${varRef}; }`);
    const textCls = `${PREFIX}-text-${key.replace(/^color-/, "")}`;
    lines.push(`.${textCls} { color: ${varRef}; }`);
  }

  lines.push(``);

  const spacingEntries = flatten(baseTokens.spacing || {}, "spacing");
  for (const [key] of spacingEntries) {
    const varRef = `var(${toCSSVar(key)})`;
    const shortKey = key.replace(/^spacing-/, "");
    lines.push(`.${PREFIX}-p-${shortKey} { padding: ${varRef}; }`);
    lines.push(`.${PREFIX}-m-${shortKey} { margin: ${varRef}; }`);
    lines.push(`.${PREFIX}-gap-${shortKey} { gap: ${varRef}; }`);
  }

  lines.push(``);

  const radiusEntries = flatten(baseTokens.radius || {}, "radius");
  for (const [key] of radiusEntries) {
    const varRef = `var(${toCSSVar(key)})`;
    const shortKey = key.replace(/^radius-/, "");
    lines.push(`.${PREFIX}-rounded-${shortKey} { border-radius: ${varRef}; }`);
  }

  lines.push(``);

  const shadowEntries = flatten(baseTokens.shadow || {}, "shadow");
  for (const [key] of shadowEntries) {
    const varRef = `var(${toCSSVar(key)})`;
    const shortKey = key.replace(/^shadow-/, "");
    lines.push(`.${PREFIX}-shadow-${shortKey} { box-shadow: ${varRef}; }`);
  }

  lines.push(``);

  const fontSizeEntries = flatten(baseTokens.font?.size || {}, "font-size");
  for (const [key] of fontSizeEntries) {
    const varRef = `var(${toCSSVar(key)})`;
    const shortKey = key.replace(/^font-size-/, "");
    lines.push(`.${PREFIX}-text-size-${shortKey} { font-size: ${varRef}; }`);
  }

  const fontWeightEntries = flatten(baseTokens.font?.weight || {}, "font-weight");
  for (const [key] of fontWeightEntries) {
    const varRef = `var(${toCSSVar(key)})`;
    const shortKey = key.replace(/^font-weight-/, "");
    lines.push(`.${PREFIX}-font-${shortKey} { font-weight: ${varRef}; }`);
  }

  lines.push(``);

  return lines.join("\n") + "\n";
}

// ---------------------------------------------------------------------------
// 3. Build Fluent UI v9 adapter — index.ts
// ---------------------------------------------------------------------------

/**
 * Produces a TypeScript file exporting a `rapidFluentTheme` object whose
 * values are CSS `var()` references, suitable for passing to
 * <FluentProvider theme={rapidFluentTheme}>.
 */
function buildFluentAdapter(baseTokens) {
  const allEntries = flatten(baseTokens);

  const lines = [];
  lines.push(`/* ============================================================`);
  lines.push(` * Rapid Design System — Fluent UI v9 Theme Adapter`);
  lines.push(` * AUTO-GENERATED by scripts/build-tokens.js — DO NOT EDIT`);
  lines.push(` * ============================================================ */`);
  lines.push(``);
  lines.push(`import type { Theme } from "@fluentui/react-components";`);
  lines.push(``);
  lines.push(`/**`);
  lines.push(` * A partial Fluent UI v9 Theme where every value is a CSS var()`);
  lines.push(` * reference into Rapid's global custom properties. This means`);
  lines.push(` * theme switching is pure CSS (via data-theme attribute) with`);
  lines.push(` * zero JS overhead.`);
  lines.push(` */`);
  lines.push(`export const rapidFluentTheme: Partial<Theme> = {`);

  const fluentMappings = buildFluentMappings(baseTokens);
  for (const [fluentKey, cssVar] of fluentMappings) {
    lines.push(`  ${fluentKey}: "var(${cssVar})",`);
  }

  lines.push(`};`);
  lines.push(``);

  return lines.join("\n") + "\n";
}

