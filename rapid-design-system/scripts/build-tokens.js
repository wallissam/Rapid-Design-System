  lines.push(` * AUTO-GENERATED by scripts/build-tokens.js — DO NOT EDIT`);
  lines.push(` *`);
  lines.push(` * Maps Bryntum's internal CSS custom properties to Rapid`);
  lines.push(` * variables so the grid inherits the active theme.`);
