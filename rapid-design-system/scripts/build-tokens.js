// ---------------------------------------------------------------------------
// 5. Build Provider.tsx (static file, not generated from tokens)
// ---------------------------------------------------------------------------

function buildProviderTSX() {
  return `/* ============================================================
 * Rapid Design System — <RapidFluentProvider>
 * AUTO-GENERATED by scripts/build-tokens.js — DO NOT EDIT
 * ============================================================ */

import React from "react";
import { FluentProvider } from "@fluentui/react-components";
import type { FluentProviderProps } from "@fluentui/react-components";
import { rapidFluentTheme } from "./index";

export type RapidFluentProviderProps = Omit<FluentProviderProps, "theme"> & {
  children: React.ReactNode;
};

/**
 * Drop-in replacement for FluentProvider that injects the Rapid
 * theme. Dark mode is driven by the \`data-theme\` attribute on
 * <html> or <body> — no JS context needed.
 */
export const RapidFluentProvider: React.FC<RapidFluentProviderProps> = ({
  children,
  ...rest
}) => {
  return (
    <FluentProvider theme={rapidFluentTheme as any} {...rest}>
      {children}
    </FluentProvider>
  );
};
`;
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function main() {
  console.log("[RDS] Reading token sources…");

  const baseTokens = readJSON(path.join(TOKENS_DIR, "base.json"));
  const darkTokens = readJSON(path.join(TOKENS_DIR, "dark.json"));

  ensureDir(CSS_DIR);
  ensureDir(FLUENT_DIR);
  ensureDir(ADAPTERS_DIR);

  // --- global.css ---
  const globalCSS = buildGlobalCSS(baseTokens, darkTokens);
  fs.writeFileSync(path.join(CSS_DIR, "global.css"), globalCSS);
  console.log("[RDS] ✓ packages/css/global.css");

  // --- utilities.css ---
  const utilitiesCSS = buildUtilitiesCSS(baseTokens);
  fs.writeFileSync(path.join(CSS_DIR, "utilities.css"), utilitiesCSS);
  console.log("[RDS] ✓ packages/css/utilities.css");

  // --- fluent-adapter/index.ts ---
  const fluentAdapter = buildFluentAdapter(baseTokens);
  fs.writeFileSync(path.join(FLUENT_DIR, "index.ts"), fluentAdapter);
  console.log("[RDS] ✓ packages/fluent-adapter/index.ts");

  // --- fluent-adapter/Provider.tsx ---
  const providerTSX = buildProviderTSX();
  fs.writeFileSync(path.join(FLUENT_DIR, "Provider.tsx"), providerTSX);
  console.log("[RDS] ✓ packages/fluent-adapter/Provider.tsx");

  // --- adapters/bryntum.css ---
  const bryntumCSS = buildBryntumAdapter(baseTokens);
  fs.writeFileSync(path.join(ADAPTERS_DIR, "bryntum.css"), bryntumCSS);
  console.log("[RDS] ✓ packages/adapters/bryntum.css");

  console.log("[RDS] Build complete.");
}

main();
